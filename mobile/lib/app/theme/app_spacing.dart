/// Centralized spacing tokens for the Sports Gurukul design system.
///
/// The application uses an 8-point spacing scale. Never use arbitrary
/// spacing values inside widgets; always reference [AppSpacing].
abstract final class AppSpacing {
  static const double none = 0;
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 20;
  static const double xxl = 24;
  static const double xxxl = 32;
  static const double xxxxl = 40;
  static const double xxxxxl = 48;
  static const double huge = 64;
}
