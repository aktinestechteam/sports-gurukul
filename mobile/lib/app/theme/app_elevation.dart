/// Centralized elevation tokens for the Sports Gurukul design system.
///
/// Elevation levels L0-L4: Flat surfaces, Cards, Floating cards,
/// Dialogs and Bottom sheets respectively.
abstract final class AppElevation {
  static const double none = 0;
  static const double card = 1;
  static const double floatingCard = 2;
  static const double dialog = 6;
  static const double bottomSheet = 12;
}
